#!/usr/bin/env python3
"""Generate/check original deterministic synthetic prototype combat sounds.

Standard-library PCM synthesis; no samples, recordings or third-party audio.
These short cues are a feedback baseline, not finished Foley or a soundtrack.
"""
import argparse
import hashlib
import io
import json
import math
from pathlib import Path
import random
import struct
import wave

ROOT = Path(__file__).resolve().parents[1]
RATE = 44100
SPECS = {
    'S_AlphaSlash': (.18, 11, 1500., 450., .08),
    'S_AlphaHit': (.20, 23, 180., 65., .55),
    'S_AlphaPoise': (.45, 37, 760., 190., .25),
    'S_AlphaRoll': (.26, 41, 420., 160., .10),
    'S_AlphaSkill': (.46, 53, 330., 880., .20),
    'S_AlphaUltimate': (.95, 67, 95., 240., .50),
}


def synthesize(name, spec):
    duration, seed, start_hz, end_hz, bass = spec
    count = round(duration * RATE)
    rng = random.Random(seed)
    samples = []
    filtered = 0.
    for index in range(count):
        t = index / RATE
        p = t / duration
        # Explicit quiet guards, smooth attack and a soft tail avoid clicks.
        attack = min(1., max(0., (t - .006) / .012))
        release = min(1., max(0., (duration - .008 - t) / .055))
        envelope = attack * release * math.exp(-p * (2.3 if 'Ultimate' in name else 3.8))
        noise = rng.uniform(-1., 1.)
        filtered += .12 * (noise - filtered)
        bright_noise = noise - filtered
        phase = 2. * math.pi * (start_hz * t + .5 * (end_hz - start_hz) * t * p)
        tone = math.sin(phase)
        low = math.sin(2. * math.pi * (70. * t - 12. * t * p))
        if name == 'S_AlphaSlash':
            signal = bright_noise * .65 + tone * .12 + low * bass
        elif name == 'S_AlphaHit':
            signal = filtered * .85 + tone * .35 + low * bass
        elif name == 'S_AlphaPoise':
            signal = bright_noise * .22 + tone * .35 + math.sin(phase * 1.53) * .18 + low * bass
        elif name == 'S_AlphaRoll':
            signal = filtered * .8 + bright_noise * .12 + tone * .07
        elif name == 'S_AlphaSkill':
            signal = tone * .28 + math.sin(phase * 1.5) * .12 + filtered * .25
        else:
            pulse = .7 + .3 * math.sin(p * math.pi * 5.)
            signal = (low * bass + tone * .24 + filtered * .55) * pulse
        samples.append(signal * envelope)
    peak = max(abs(value) for value in samples)
    pcm = [round(value / peak * .72 * 32767) for value in samples]
    payload = struct.pack('<' + 'h' * len(pcm), *pcm)
    out = io.BytesIO()
    with wave.open(out, 'wb') as audio:
        audio.setnchannels(1)
        audio.setsampwidth(2)
        audio.setframerate(RATE)
        audio.writeframes(payload)
    data = out.getvalue()
    rms = math.sqrt(sum((value / 32768.) ** 2 for value in pcm) / len(pcm))
    assert all(value == 0 for value in pcm[:round(.006 * RATE)])
    assert all(value == 0 for value in pcm[-round(.006 * RATE):])
    assert max(abs(value) for value in pcm) < 32767
    assert .01 < rms < .4
    return data, {
        'file': name + '.wav', 'duration_seconds': len(pcm) / RATE,
        'sample_rate': RATE, 'channels': 1, 'bits_per_sample': 16,
        'peak_dbfs': round(20. * math.log10(max(abs(value) for value in pcm) / 32768.), 3),
        'rms_dbfs': round(20. * math.log10(rms), 3),
        'sha256': hashlib.sha256(data).hexdigest(),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Validate checked-in sources without modifying them')
    parser.add_argument('--output', type=Path, default=ROOT / 'SourceAudio')
    args = parser.parse_args()
    sources = []
    if not args.check:
        args.output.mkdir(parents=True, exist_ok=True)
    for name, spec in SPECS.items():
        data, metadata = synthesize(name, spec)
        path = args.output / metadata['file']
        if args.check:
            if not path.is_file() or path.read_bytes() != data:
                raise RuntimeError(f'Missing or stale generated audio: {path}')
        else:
            path.write_bytes(data)
        with wave.open(io.BytesIO(data), 'rb') as audio:
            assert audio.getnchannels() == 1 and audio.getsampwidth() == 2
            assert audio.getframerate() == RATE and audio.getcomptype() == 'NONE'
        sources.append(metadata)
    manifest = {
        'generator': 'AlphaGame.SyntheticAudio.v1',
        'origin': 'Original deterministic PCM synthesis; no external samples or recordings.',
        'purpose': 'Prototype combat feedback; not finished Foley, voice acting or music.',
        'validation': 'PCM format, exact generated bytes, head/tail silence, peak and RMS checked; UE playback not verified.',
        'sources': sources,
    }
    text = json.dumps(manifest, indent=2) + '\n'
    manifest_path = args.output / 'manifest.json'
    if args.check:
        if manifest_path.read_text(encoding='utf-8') != text:
            raise RuntimeError('Audio source manifest differs from generated measurements')
    else:
        manifest_path.write_text(text, encoding='utf-8')
    print(f'PASS: {len(sources)} original mono PCM16 cues, peak/RMS/quiet guards and source hashes')
    for entry in sources:
        print(f'{entry["file"]}: {entry["duration_seconds"]:.2f}s, peak {entry["peak_dbfs"]:.1f} dBFS, RMS {entry["rms_dbfs"]:.1f} dBFS')


if __name__ == '__main__':
    main()
